import {xml,markdown} from './format.mjs';
import {buildModules} from './modules.mjs';

function image(module,assets){
  const paths=assets[module.id]||{
    desktop:`assets/generated/${module.id}.svg`,
    mobile:`assets/generated/${module.id}-mobile.svg`,
    still:`assets/generated/${module.id}-still.svg`,
    mobileStill:`assets/generated/${module.id}-mobile-still.svg`
  };
  const picture=`<picture><source media="(prefers-reduced-motion: reduce) and (max-width: 600px)" srcset="${paths.mobileStill}"><source media="(prefers-reduced-motion: reduce)" srcset="${paths.still}"><source media="(max-width: 600px)" srcset="${paths.mobile}"><img src="${paths.desktop}" width="100%" alt="${xml(module.alt)}"></picture>`;
  return `<a href="${xml(module.href)}">${picture}</a>`;
}

function table(rows){
  return rows.map(row=>`<table role="presentation" width="100%" border="0" cellpadding="0" cellspacing="0"><tbody><tr>${row.map(cell=>`<td width="${Math.floor(100/row.length)}%" valign="top">${cell||'&nbsp;'}</td>`).join('')}</tr></tbody></table>`).join('\n');
}

function paired(left,right,assets){
  const leftColumn=left.map(module=>image(module,assets)).join('<br>');
  const rightColumn=right.map(module=>image(module,assets)).join('<br>');
  return left.length||right.length?table([[leftColumn,rightColumn]]):'';
}

function imageGrid(items,columns,assets){
  const rows=[];
  for(let i=0;i<items.length;i+=columns)rows.push(Array.from({length:columns},(_,j)=>items[i+j]?image(items[i+j],assets):''));
  return rows.length?table(rows):'';
}

export function renderReadme(data,config,assets={}){
  const modules=buildModules(data,config),byId=new Map(modules.map(module=>[module.id,module]));
  const identity=byId.get('identity');
  const gauge=byId.get('contribution-record');
  const spotlight=byId.get('spotlight');
  const proposal=byId.get('resolved-pr');
  const metrics=byId.get('metrics');
  const projects=modules.filter(module=>/^project-\d+$/.test(module.id)||module.id==='project-empty');
  const contributions=modules.filter(module=>module.id==='contribution-records'||module.id==='contribution-empty');
  const showcases=modules.filter(module=>/^showcase-\d+$/.test(module.id));
  const impact=byId.get('impact');
  const activities=modules.filter(module=>/^activity-\d+$/.test(module.id));
  const footer=byId.get('footer');
  const sections=[
    `<p>${image(identity,assets)}</p>`,
    table([[`${image(gauge,assets)}`,`${image(spotlight,assets)}${proposal?`<br>${image(proposal,assets)}`:''}`]]),
    `<p>${image(metrics,assets)}</p>`,
    paired(projects,contributions,assets),
    imageGrid(showcases,2,assets),
    impact?`<p>${image(impact,assets)}</p>`:'',
    imageGrid(activities,3,assets),
    `<p>${image(footer,assets)}</p>`,
    Object.entries(config.links).map(([label,url])=>`[${markdown(label)}](${url})`).join(' · ')
  ].filter(Boolean);
  return `<!-- Generated by scripts/update-profile.mjs. Edit profile.config.json for content. -->\n${sections.join('\n\n')}\n`;
}

