import {xml,markdown,compact} from './format.mjs';

export function renderReadme(data,config,assets={desktop:'assets/profile.svg',mobile:'assets/profile-mobile.svg',still:'assets/profile-still.svg',mobileStill:'assets/profile-mobile-still.svg'}){
  const s=data.spotlight,query=encodeURIComponent(`author:${config.username} is:pr is:merged is:public -user:${config.username}`);
  const projects=data.projects.slice(0,config.projects.maxVisible);
  const links=[...(s?[`[PR #${s.number}](${s.url})`]:[]),...projects.map(p=>`[${markdown(p.name)}](${p.url})`),`[All projects](https://github.com/${config.username}?tab=repositories)`,`[Merged contributions](https://github.com/search?q=${query}&type=pullrequests)`];
  return `<!-- Generated by scripts/update-profile.mjs. Edit profile.config.json for content. -->
<picture>
  <source media="(prefers-reduced-motion: reduce) and (max-width: 600px)" srcset="${assets.mobileStill}">
  <source media="(prefers-reduced-motion: reduce)" srcset="${assets.still}">
  <source media="(max-width: 600px)" srcset="${assets.mobile}">
  <img src="${assets.desktop}" width="100%" alt="${xml(config.name)} — ${data.mergedPullRequests} merged upstream PRs and ${data.projects.length} public ${data.projects.length===1?'project':'projects'}, with projects and contribution details">
</picture>

${links.join(' · ')}

${Object.entries(config.links).map(([label,url])=>`[${markdown(label)}](${url})`).join(' · ')}

<details>
<summary>Text version and project links</summary>

${markdown(config.bio)}

${s?`- **PR** · [${markdown(s.repoName)}](${s.repoUrl}) · **${compact(s.stars)} stars / ${compact(s.forks)} forks** · [${markdown(s.title)} — #${s.number}](${s.url}) (${s.status})\n`:''}- **Contributor** · [${data.mergedPullRequests} merged upstream PRs](https://github.com/search?q=${query}&type=pullrequests)
${projects.map(p=>`- **Project** · [${markdown(p.name)}](${p.url}) · ${markdown(p.description)}`).join('\n')}
${data.projects.length>projects.length?`\n[All ${data.projects.length} projects →](https://github.com/${config.username}?tab=repositories)\n`:''}
${data.contributions.map(c=>`\n**${markdown(c.repo)}** · ${c.count} merged PRs\n\n${(c.pulls||[]).map(pr=>`- [#${pr.number}: ${markdown(pr.title)}](${pr.url})`).join('\n')}`).join('\n')}

</details>
`;
}
